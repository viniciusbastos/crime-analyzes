class IbgeDataSyncService:
    """Service for synchronizing IBGE data"""

    def __init__(self):
        self.batch_size = 10  # Process municipalities in batches
        self.delay_between_batches = 5  # Seconds between batches

    def sync_municipalities_data(self, municipality_codes: List[str], year: int = None) -> Dict[str, Any]:
        """Sync demographic data for multiple municipalities"""
        if not year:
            year = datetime.now().year - 1

        results = {
            'total_processed': 0,
            'successful': 0,
            'failed': 0,
            'errors': [],
            'year': year
        }

        # Process in batches to avoid overwhelming the API
        for i in range(0, len(municipality_codes), self.batch_size):
            batch = municipality_codes[i:i + self.batch_size]

            for code in batch:
                try:
                    results['total_processed'] += 1

                    # Get data from IBGE API
                    data = ibge_service.get_municipality_data(code, year)

                    if data:
                        # Save to database
                        success = ibge_service.save_demographic_data(data)
                        if success:
                            results['successful'] += 1
                            logger.info(f"Successfully synced data for municipality {code}")
                        else:
                            results['failed'] += 1
                            results['errors'].append(f"Failed to save data for {code}")
                    else:
                        results['failed'] += 1
                        results['errors'].append(f"No data available for municipality {code}")

                except Exception as e:
                    results['failed'] += 1
                    error_msg = f"Error syncing municipality {code}: {str(e)}"
                    results['errors'].append(error_msg)
                    logger.error(error_msg)

            # Delay between batches to respect API rate limits
            if i + self.batch_size < len(municipality_codes):
                logger.info(f"Processed batch {i//self.batch_size + 1}, waiting {self.delay_between_batches} seconds...")
                time.sleep(self.delay_between_batches)

        return results

