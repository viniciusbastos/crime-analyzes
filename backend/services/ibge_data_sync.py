    def get_sync_status(self) -> Dict[str, Any]:
        """Get current synchronization status"""
        try:
            total_records = IbgeDemographicData.query.count()
            latest_update = db.session.query(db.func.max(IbgeDemographicData.last_updated)).scalar()

            # Count records by year
            year_counts = db.session.query(
                IbgeDemographicData.year,
                db.func.count(IbgeDemographicData.id)
            ).group_by(IbgeDemographicData.year).all()

            return {
                'total_records': total_records,
                'latest_update': latest_update.isoformat() if latest_update else None,
                'records_by_year': {str(year): count for year, count in year_counts}
            }

        except Exception as e:
            logger.error(f"Error getting sync status: {e}")
            return {'error': str(e)}

    def cleanup_old_data(self, days_to_keep: int = 365) -> int:
        """Clean up old IBGE data cache entries"""
        try:
            cutoff_date = datetime.utcnow() - timedelta(days=days_to_keep)

            deleted_count = db.session.query(IbgeDataCache).filter(
                IbgeDataCache.created_at < cutoff_date
            ).delete()

            db.session.commit()
            logger.info(f"Cleaned up {deleted_count} old IBGE cache entries")
            return deleted_count

        except Exception as e:
            logger.error(f"Error cleaning up old data: {e}")
            db.session.rollback()
            return 0


